internal fun resolveUiLanguage(requested:String,systemTag:String):String {
    when(requested.trim()) {
        "en" -> return "en"
        "zh-CN","zh" -> return "zh-CN"
        "zh-TW","zh-HK","zh-MO" -> return "zh-TW"
        "ja","ko","fa","ru" -> return requested.trim()
    }
    val tag=systemTag.lowercase(Locale.ROOT).replace('_','-')
    return when {
        tag.startsWith("zh-tw") || tag.startsWith("zh-hk") || tag.startsWith("zh-mo") -> "zh-TW"
        tag.startsWith("zh") -> "zh-CN"
        tag.startsWith("ja") -> "ja"
        tag.startsWith("ko") -> "ko"
        tag.startsWith("fa") -> "fa"
        tag.startsWith("ru") -> "ru"
        else -> "en"
    }
}

