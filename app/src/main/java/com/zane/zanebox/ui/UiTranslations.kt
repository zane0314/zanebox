@Composable
internal fun UiLanguageProvider(data:AppData,content:@Composable ()->Unit) {
    val language=resolveUiLanguage(data.setting("appLanguage"),Locale.getDefault().toLanguageTag())
    CompositionLocalProvider(LocalUiLanguage provides language,content=content)
}

@Composable
internal fun uiText(value:String):String {
    return translateText(value,LocalUiLanguage.current)
}

/** Pure lookup used by Compose and directly suitable for a small JUnit test. */
internal fun translateText(source:String,language:String):String {
    val native=nativeUiLabels[source]?.get(language)
    val base=translations[source]
    val extra=additionalTranslations[source]
    return when(language.lowercase(Locale.ROOT)) {
        "ja" -> extra?.ja ?: base?.english ?: native ?: source
        "ko" -> extra?.ko ?: base?.english ?: native ?: source
        "fa" -> extra?.fa ?: base?.english ?: native ?: source
        "ru" -> extra?.ru ?: base?.english ?: native ?: source
        "en" -> base?.english ?: native ?: source
        "zh-tw","zh-hk","zh-mo" -> base?.traditional ?: native ?: source
        else -> base?.simplified ?: source
    }
}

